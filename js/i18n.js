function pick() {
  try {
    const v = localStorage.getItem(KEY);
    if (DICT[v]) return v;
  } catch { /* 프라이빗 모드 */ }
  // 처음 열 때는 기기 언어를 따른다. 일본어 기기면 일본어로 시작한다.
  return (navigator.language || '').toLowerCase().startsWith('ja') ? 'ja' : 'ko';
}

let lang = pick();

export const getLang = () => lang;

/** 숫자·날짜 서식에 쓰는 로케일. */
export const locale = () => (lang === 'ja' ? 'ja-JP' : 'ko-KR');

export function setLang(k) {
  if (!DICT[k]) return lang;
  lang = k;
  try { localStorage.setItem(KEY, k); } catch { /* 프라이빗 모드 */ }
  document.documentElement.lang = k;
  return lang;
}

/**
 * 문자열 하나. `{name}` 자리는 vars 로 채운다.
 * 키가 없으면 한국어로, 한국어에도 없으면 키를 그대로 돌려준다 —
 * 화면에 키가 보이면 바로 눈에 띄어 빠진 번역을 찾기 쉽다.
 */
export function t(key, vars) {
  let s = DICT[lang][key] ?? DICT.ko[key] ?? key;
  if (vars) {
    for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
  }
  return s;
}

document.documentElement.lang = lang;
